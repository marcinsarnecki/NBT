"""Write the legacy palette regression fixture from its on-disk format."""

import argparse
from pathlib import Path
import struct
import zlib


FIXTURE = (Path(__file__).resolve().parents[1] / "src/test/resources/net/querz/mca"
           / "palettes/legacy/r.0.1.mca")
SECTOR_SIZE = 4096


def nbt_string(value):
    encoded = value.encode("ascii")
    return struct.pack(">H", len(encoded)) + encoded


def named_tag(tag_type, name, payload):
    return bytes([tag_type]) + nbt_string(name) + payload


def compound(*tags):
    return b"".join(tags) + b"\0"


def compound_list(name, entries):
    return named_tag(9, name, struct.pack(">BI", 10, len(entries)) + b"".join(entries))


def block_state(name, **properties):
    name_tag = named_tag(8, "Name", nbt_string("minecraft:" + name))
    if not properties:
        return compound(name_tag)
    property_tags = [named_tag(8, key, nbt_string(value)) for key, value in properties.items()]
    return compound(name_tag, named_tag(10, "Properties", compound(*property_tags)))


def terrain_section():
    # The initial 16 entries fill the four-bit range. A new state requires five bits.
    palette = [
        block_state("air"),
        block_state("bedrock"),
        block_state("dirt"),
        block_state("grass_block"),
        block_state("deepslate", axis="y"),
        block_state("oak_log", axis="x"),
        block_state("wall_torch", facing="west"),
        block_state("oak_stairs", facing="west", half="top", shape="straight", waterlogged="false"),
        block_state("redstone_ore", lit="false"),
        block_state("lava", level="0"),
        block_state("white_concrete"),
        block_state("orange_concrete"),
        block_state("magenta_concrete"),
        block_state("light_blue_concrete"),
        block_state("yellow_concrete"),
        block_state("lime_concrete"),
    ]
    indices = [1] * 256 + [2] * 512 + [3] * 256 + [0] * 3072
    # At block (3,-63,512) and one other position, use the same deepslate state.
    indices[256 + 3] = 4
    indices[256 + 16 + 13] = 4
    for offset, index in enumerate(range(5, 16)):
        indices[4 * 256 + 16 + offset] = index
        indices[4095 - offset] = index
    # X varies fastest, then Z, then Y. Each long starts with its lowest nibble.
    words = [
        sum(index << (4 * i) for i, index in enumerate(indices[start:start + 16]))
        for start in range(0, len(indices), 16)
    ]
    packed = struct.pack(">I", len(words)) + b"".join(struct.pack(">Q", word) for word in words)
    return section(-4, palette, named_tag(12, "data", packed))


def section(y, palette, *block_data):
    states = compound(compound_list("palette", palette), *block_data)
    biomes = compound(named_tag(9, "palette", struct.pack(">BI", 8, 1) + nbt_string("minecraft:plains")))
    return compound(named_tag(1, "Y", struct.pack(">b", y)),
                    named_tag(10, "block_states", states),
                    named_tag(10, "biomes", biomes))


def region_bytes():
    chunk = compound(
        named_tag(3, "DataVersion", struct.pack(">i", 4790)),
        named_tag(3, "xPos", struct.pack(">i", 0)),
        named_tag(3, "yPos", struct.pack(">i", -4)),
        named_tag(3, "zPos", struct.pack(">i", 32)),
        named_tag(8, "Status", nbt_string("minecraft:full")),
        named_tag(4, "LastUpdate", struct.pack(">q", 0)),
        named_tag(4, "InhabitedTime", struct.pack(">q", 0)),
        compound_list("sections", [terrain_section(), section(-3, [block_state("air")])]),
        compound_list("block_entities", []),
        compound_list("block_ticks", []),
        compound_list("fluid_ticks", []),
    )
    nbt = named_tag(10, "", chunk)
    # One stored DEFLATE block inside a ZLIB stream. This fixes the bytes
    # independently of compression heuristics and leaves the record type as ZLIB.
    zlib_stream = (b"\x78\x01\x01" + struct.pack("<HH", len(nbt), len(nbt) ^ 0xffff)
                   + nbt + struct.pack(">I", zlib.adler32(nbt)))
    record = struct.pack(">IB", len(zlib_stream) + 1, 2) + zlib_stream
    sectors = (len(record) + SECTOR_SIZE - 1) // SECTOR_SIZE
    # r.0.1.mca owns chunk (0,32) at slot zero. Offsets start after the two headers.
    locations = struct.pack(">I", (2 << 8) | sectors).ljust(SECTOR_SIZE, b"\0")
    timestamps = bytes(SECTOR_SIZE)
    return locations + timestamps + record.ljust(sectors * SECTOR_SIZE, b"\0")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="check the fixture without writing it")
    args = parser.parse_args()
    generated = region_bytes()
    if args.check:
        if not FIXTURE.is_file() or FIXTURE.read_bytes() != generated:
            parser.exit(1, "Legacy fixture differs from the independently generated bytes.\n")
    else:
        FIXTURE.write_bytes(generated)


if __name__ == "__main__":
    main()
